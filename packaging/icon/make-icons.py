#!/usr/bin/env python3
"""Renders packaging/icon/peekstep.svg into every icon file the builds use.

Run it after changing the SVG and commit the results:

    pip install cairosvg pillow
    python3 packaging/icon/make-icons.py

Writes:
  packaging/windows/peekstep.ico            exe resource and installer
  packaging/macos/Peekstep.icns             app bundle
  packaging/linux/icons/hicolor/...         menu entry (install.sh)
  src/platform/WindowIconData.h             window icon on Linux/X11
"""
import io
import pathlib
import shutil

import cairosvg
from PIL import Image

root = pathlib.Path(__file__).resolve().parents[2]
svg = root / "packaging/icon/peekstep.svg"


def render(size):
    # Render each size from the vector source, sharper than scaling one bitmap.
    png = cairosvg.svg2png(url=str(svg), output_width=size, output_height=size)
    return Image.open(io.BytesIO(png)).convert("RGBA")


# Windows: Explorer and the taskbar pick from these sizes.
ico_sizes = [16, 20, 24, 32, 40, 48, 64, 128, 256]
images = [render(s) for s in ico_sizes]
images[-1].save(root / "packaging/windows/peekstep.ico", format="ICO",
                sizes=[(s, s) for s in ico_sizes], append_images=images[:-1])

# macOS: Pillow builds the .icns from the 1024 px image (all standard sizes).
render(1024).save(root / "packaging/macos/Peekstep.icns", format="ICNS")

# Linux: freedesktop hicolor theme.
hicolor = root / "packaging/linux/icons/hicolor"
shutil.rmtree(hicolor, ignore_errors=True)
for s in [16, 24, 32, 48, 64, 128, 256, 512]:
    d = hicolor / f"{s}x{s}/apps"
    d.mkdir(parents=True)
    render(s).save(d / "peekstep.png", optimize=True)
(hicolor / "scalable/apps").mkdir(parents=True)
shutil.copy(svg, hicolor / "scalable/apps/peekstep.svg")

# Window icon for GLFW (X11 shows it in the title bar and task switcher).
win_sizes = [16, 32, 48, 64]
out = ["// Generated by packaging/icon/make-icons.py from peekstep.svg. Do not edit.",
       "#pragma once", "", "namespace peekstep_icon {", ""]
for s in win_sizes:
    data = render(s).tobytes()
    out.append(f"inline constexpr unsigned char rgba{s}[] = {{")
    for i in range(0, len(data), 24):
        out.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    out.append("};")
out += ["", "struct Size { int px; const unsigned char* rgba; };",
        "inline constexpr Size sizes[] = {" + ", ".join(f"{{{s}, rgba{s}}}" for s in win_sizes) + "};",
        "", "}  // namespace peekstep_icon", ""]
(root / "src/platform/WindowIconData.h").write_text("\n".join(out))
print("Icons written.")
